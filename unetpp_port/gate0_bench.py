"""
Gate-0 synthetic benchmark: real network/optimizer machinery, dummy data (no PanTS needed).

Why this exists: we don't have the real nnU-Net plans.json yet (it only gets generated by running
the planner on the actual PanTS dataset, which needs the ~300GB download nobody has started). So the
*real* patch size / n_stages / features_per_stage are unknown. This script can't answer "will the
real config fit" with certainty -- only running the real planner on real data can. What it CAN answer,
today, with zero data: relative behavior of the architecture itself -- batch-size memory/time scaling,
DS-on vs DS-off vs paper-averaging cost, and whether a code-level optimization (dead-head skipping)
is correct and actually faster. Treat every patch size below as a stress-test bound, not a confirmed
real value.

Kill-fast: each config is wrapped in try/except. An OOM or crash is logged and we move to the next
config instead of dying. Nothing here runs for more than a couple minutes per config.
"""
import gc
import json
import sys
import time
import traceback

import torch
from torch import nn

sys.path.insert(0, ".")
from smoke_test import build  # noqa: E402  (reuses the already-verified model constructor)

DEVICE = "cuda"
NUM_CLASSES = 28
WARMUP = 5
STEPS = 20


def make_targets(deep_supervision, n_outputs, batch_size, patch_size, device):
    if deep_supervision:
        return [torch.randint(0, NUM_CLASSES, (batch_size, *patch_size), device=device) for _ in range(n_outputs)]
    return torch.randint(0, NUM_CLASSES, (batch_size, *patch_size), device=device)


def run_steps(model, x, y, deep_supervision, opt, ce):
    torch.cuda.synchronize()
    t0 = time.time()
    opt.zero_grad(set_to_none=True)
    out = model(x)
    if deep_supervision:
        loss = sum(ce(o, yy) for o, yy in zip(out, y)) / len(out)
    else:
        loss = ce(out, y)
    loss.backward()
    opt.step()
    torch.cuda.synchronize()
    return time.time() - t0


def bench_config(n_stages, patch_size, batch_size, deep_supervision, label):
    result = {"label": label, "n_stages": n_stages, "patch_size": patch_size,
              "batch_size": batch_size, "deep_supervision": deep_supervision}
    try:
        model = build(n_stages, deep_supervision).to(DEVICE)
        n_outputs = n_stages - 1
        opt = torch.optim.SGD(model.parameters(), lr=1e-2, momentum=0.99, nesterov=True)
        ce = nn.CrossEntropyLoss()
        x = torch.rand((batch_size, 1, *patch_size), device=DEVICE)
        y = make_targets(deep_supervision, n_outputs, batch_size, patch_size, DEVICE)

        torch.cuda.reset_peak_memory_stats()
        times = []
        for i in range(WARMUP + STEPS):
            t = run_steps(model, x, y, deep_supervision, opt, ce)
            if i >= WARMUP:
                times.append(t)
        times.sort()
        result.update({
            "ok": True,
            "mean_s_per_step": sum(times) / len(times),
            "p50_s_per_step": times[len(times) // 2],
            "peak_mem_gb": torch.cuda.max_memory_allocated() / 1e9,
            "params": sum(p.numel() for p in model.parameters()),
        })
    except torch.cuda.OutOfMemoryError as e:
        result.update({"ok": False, "error": "OOM", "detail": str(e)[:200]})
    except Exception as e:
        result.update({"ok": False, "error": type(e).__name__, "detail": str(e)[:300]})
    finally:
        try:
            del model, opt, x, y
        except Exception:
            pass
        gc.collect()
        torch.cuda.empty_cache()
    return result


def try_compile_once():
    """Kill-fast check: does torch.compile even survive one step on this box right now."""
    try:
        model = build(5, True).to(DEVICE)
        model = torch.compile(model)
        opt = torch.optim.SGD(model.parameters(), lr=1e-2)
        ce = nn.CrossEntropyLoss()
        patch = (32, 64, 64)
        x = torch.rand((1, 1, *patch), device=DEVICE)
        y = make_targets(True, 4, 1, patch, DEVICE)
        t = run_steps(model, x, y, True, opt, ce)
        return {"ok": True, "first_step_s": t}
    except Exception as e:
        return {"ok": False, "error": type(e).__name__, "detail": str(e)[:300]}
    finally:
        gc.collect()
        torch.cuda.empty_cache()


def main():
    print(f"torch {torch.__version__} cuda_ok={torch.cuda.is_available()}", flush=True)
    if torch.cuda.is_available():
        print(f"device: {torch.cuda.get_device_name(0)}", flush=True)

    results = {"compile_check": None, "batch_sweep": [], "ds_variant_sweep": []}

    print("\n=== [1/3] torch.compile kill-fast check ===", flush=True)
    results["compile_check"] = try_compile_once()
    print(json.dumps(results["compile_check"]), flush=True)

    print("\n=== [2/3] batch-size memory/time sweep (stress-bound patch sizes) ===", flush=True)
    # n_stages=6 roughly matches a 6-downsample 3D full-res config; patch sizes span a plausible
    # conservative-to-aggressive range since the real planner output isn't available yet.
    patch_candidates = [(64, 128, 128), (96, 160, 160)]
    for patch in patch_candidates:
        for bs in (1, 2, 4):
            label = f"unetpp_n6_ds_on_patch{patch}_bs{bs}"
            print(f"--- {label} ---", flush=True)
            r = bench_config(n_stages=6, patch_size=patch, batch_size=bs, deep_supervision=True, label=label)
            print(json.dumps(r), flush=True)
            results["batch_sweep"].append(r)
            if not r["ok"] and r.get("error") == "OOM":
                print(f"OOM at bs={bs}, patch={patch} -- skipping larger batch sizes for this patch", flush=True)
                break

    print("\n=== [3/3] DS-on vs DS-off relative cost, fixed patch/batch ===", flush=True)
    fixed_patch = (64, 128, 128)
    fixed_bs = 2
    for ds in (True, False):
        label = f"unetpp_n6_ds{ds}_patch{fixed_patch}_bs{fixed_bs}"
        print(f"--- {label} ---", flush=True)
        r = bench_config(n_stages=6, patch_size=fixed_patch, batch_size=fixed_bs, deep_supervision=ds, label=label)
        print(json.dumps(r), flush=True)
        results["ds_variant_sweep"].append(r)

    with open("gate0_results.json", "w") as f:
        json.dump(results, f, indent=2)
    print("\nGATE0_DONE", flush=True)


if __name__ == "__main__":
    main()
